import { readFile, writeFile, unlink } from 'node:fs/promises';
import assert from 'node:assert/strict';
const path='private/appsumo-upload-ticket.json';
const ticket=JSON.parse(await readFile(path,'utf8'));
const csv=await readFile('private/counterkeep-appsumo-codes.csv');
const rows=csv.toString('utf8').trimEnd().split(/\r?\n/);
const codes=rows.slice(1);
assert.equal(rows[0],'code');assert.equal(codes.length,1000);
assert.equal(new Set(codes).size,codes.length);
assert.ok(codes.every(code=>/^[A-Za-z0-9_-]{3,200}$/.test(code)));
assert.ok(codes.length>=ticket.min_codes && rows.length<=ticket.max_codes);
assert.ok(csv.length<=ticket.max_bytes);
assert.equal(ticket.upload_url,'https://appsumo.com/api/selfsubmission-codes-uploads/');
assert.equal(ticket.existing_files.length,0,'Refusing to replace an unexpected existing codes file');
assert.equal(ticket.replaces_existing,false);
const form=new FormData();form.append('ticket',ticket.ticket);form.append('file',new Blob([csv],{type:'text/csv'}),'counterkeep-appsumo-codes.csv');
const response=await fetch(ticket.upload_url,{method:'POST',body:form,redirect:'error',signal:AbortSignal.timeout(60000)});
const text=await response.text();
await writeFile('private/appsumo-upload-result.json',text,{mode:0o600});
if(!response.ok)throw Error(`AppSumo code upload returned HTTP ${response.status}; details saved privately, no code or credential printed`);
await unlink(path);
console.log(`AppSumo accepted the private 1000-code CSV (HTTP ${response.status}). One-time ticket removed. Confirm count using get_submission.`);
